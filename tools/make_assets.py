"""Regenerates icons.py (the wire-globe button icon, embedded as PNG) and assets/zoneentry.ico.

Only needed if you want to change the artwork:   pip install pillow  &&  python tools/make_assets.py
The app itself does NOT need Pillow.
"""
import base64
import io
from pathlib import Path

from PIL import Image, ImageChops, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
GLOBE_SIZES = (16, 20, 24, 28, 32, 40, 48)  # picked at runtime to suit the Windows display scaling
LINE = (60, 60, 60)


def globe(size: int) -> Image.Image:
    """Wire globe: ring, meridian ellipse, centre line, equator (+ two parallels when large enough)."""
    k = 8  # draw 8x bigger, then shrink for smooth anti-aliasing
    S = size * k
    pad = S * 0.07
    box = [pad, pad, S - pad, S - pad]
    cx = cy = S / 2
    r = (S - 2 * pad) / 2
    w = max(round(S * 0.075), k)

    inner = Image.new("L", (S, S), 0)
    d = ImageDraw.Draw(inner)
    ew = r * 0.5
    d.ellipse([cx - ew, cy - r, cx + ew, cy + r], outline=255, width=w)
    d.line([cx, cy - r, cx, cy + r], fill=255, width=w)
    d.line([cx - r, cy, cx + r, cy], fill=255, width=w)
    if size >= 24:
        for dy in (-0.5, 0.5):
            d.line([cx - r, cy + dy * r, cx + r, cy + dy * r], fill=255, width=w)
    mask = Image.new("L", (S, S), 0)
    ImageDraw.Draw(mask).ellipse(box, fill=255)
    inner = ImageChops.multiply(inner, mask)  # keep inner lines inside the circle

    ring = Image.new("L", (S, S), 0)
    ImageDraw.Draw(ring).ellipse(box, outline=255, width=w)
    alpha = ImageChops.lighter(inner, ring)

    out = Image.new("RGBA", (S, S), LINE + (0,))
    out.putalpha(alpha)
    return out.resize((size, size), Image.LANCZOS)


def app_icon(size: int = 512) -> Image.Image:
    """Blue rounded tile with a white shelving unit and a few boxes."""
    img = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    u = size / 256
    d.rounded_rectangle([8 * u, 8 * u, 248 * u, 248 * u], radius=52 * u, fill=(31, 95, 168, 255))
    white, box = (255, 255, 255, 255), (170, 210, 250, 255)
    # boxes on the shelves
    for x0, x1, y1, h in ((78, 112, 96, 30), (122, 150, 96, 24), (160, 182, 96, 34),
                          (78, 98, 150, 26), (108, 150, 150, 34), (160, 182, 150, 22),
                          (84, 128, 204, 30), (138, 182, 204, 36)):
        d.rounded_rectangle([x0 * u, (y1 - h) * u, x1 * u, y1 * u], radius=4 * u, fill=box)
    # uprights + three shelves
    for x in (60, 188):
        d.rounded_rectangle([x * u, 48 * u, (x + 10) * u, 214 * u], radius=3 * u, fill=white)
    for y in (96, 150, 204):
        d.rounded_rectangle([60 * u, y * u, 198 * u, (y + 10) * u], radius=3 * u, fill=white)
    return img


def main() -> None:
    lines = ['"""Generated by tools/make_assets.py - do not edit by hand."""', "", "GLOBE_PNG = {"]
    for s in GLOBE_SIZES:
        buf = io.BytesIO()
        globe(s).save(buf, "PNG", optimize=True)
        lines.append(f'    {s}: "{base64.b64encode(buf.getvalue()).decode()}",')
    lines.append("}")
    (ROOT / "icons.py").write_text("\n".join(lines) + "\n", encoding="ascii")

    icon = app_icon(512)
    out = ROOT / "assets" / "zoneentry.ico"
    icon.save(out, format="ICO", sizes=[(16, 16), (24, 24), (32, 32), (48, 48), (64, 64), (128, 128), (256, 256)])
    icon.resize((256, 256), Image.LANCZOS).save(ROOT / "docs" / "icon.png")
    print("wrote icons.py,", out.relative_to(ROOT))


if __name__ == "__main__":
    main()
